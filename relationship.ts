function splitPlayerName(name: string, explicitFamily?: string, explicitGiven?: string) {
  const normalized = name.trim().replace(/\s+/g, ' ');
  if (!normalized) return null;

  // 优先使用显式提供的姓名（解决双字姓等问题）
  if (explicitFamily && explicitGiven) {
    return {
      fullName: normalized,
      familyName: explicitFamily.trim(),
      givenName: explicitGiven.trim(),
    };
  }

  // 回退到自动拆分逻辑
  const parts = normalized.split(' ').filter(Boolean);
  if (parts.length >= 2) {
    return {
      fullName: normalized,
      familyName: parts[0],
      givenName: parts.slice(1).join(' '),
    };
  }

  const compact = normalized.replace(/[・·]/g, '');
  if (/^[一-鿿]{2,4}$/.test(compact)) {
    const familyLength = compact.length >= 4 ? 2 : 1;
    return {
      fullName: compact,
      familyName: compact.slice(0, familyLength),
      givenName: compact.slice(familyLength) || compact,
    };
  }

  return {
    fullName: normalized,
    familyName: normalized,
    givenName: normalized,
  };
}

